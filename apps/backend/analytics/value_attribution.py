class ValueAttributionService:
    """
    Service for attributing value to artifacts and actions.

    Maps artifact types to value categories and calculates
    the business value based on configurable multipliers.
    """

    def __init__(
        self,
        value_overrides: Optional[Dict[ValueCategory, float]] = None,
        hourly_rate: float = 150.0,
    ):
        """
        Initialize the value attribution service.

        Args:
            value_overrides: Optional overrides for default values per category
            hourly_rate: Developer hourly rate for time-based calculations
        """
        self.values = {**DEFAULT_VALUES}
        if value_overrides:
            self.values.update(value_overrides)
        self.hourly_rate = hourly_rate

    def attribute_value(
        self,
        artifact_type: str,
        content: str,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> ValueAttribution:
        """
        Attribute value to an artifact based on its type and content.

        Args:
            artifact_type: The type of artifact (e.g., "code_implementation")
            content: The artifact content
            metadata: Additional metadata about the artifact

        Returns:
            ValueAttribution with calculated value and category
        """
        metadata = metadata or {}

        # Map artifact type to category
        category = ARTIFACT_TYPE_MAPPING.get(
            artifact_type,
            self._infer_category_from_content(content, artifact_type)
        )

        # Calculate value based on category and content
        value_usd = self._calculate_value(category, content, metadata)

        # Calculate confidence based on available evidence
        confidence = self._calculate_confidence(category, content, metadata)

        # Build evidence list
        evidence = self._build_evidence(metadata)

        return ValueAttribution(
            category=category,
            parent_type=CATEGORY_PARENT_MAP.get(category, "other"),
            value_usd=value_usd,
            confidence=confidence,
            evidence=evidence,
            metadata=metadata,
        )

    def _infer_category_from_content(
        self,
        content: str,
        artifact_type: str,
    ) -> ValueCategory:
        """Infer category from content when type is not mapped."""
        content_lower = content.lower()

        # Check for security-related content
        if any(kw in content_lower for kw in ["security", "vulnerability", "exploit", "injection"]):
            return ValueCategory.SECURITY_ISSUE_FOUND

        # Check for performance content
        if any(kw in content_lower for kw in ["performance", "latency", "bottleneck", "slow"]):
            return ValueCategory.PERFORMANCE_ISSUE_FOUND

        # Check for documentation content
        if any(kw in content_lower for kw in ["documentation", "readme", "guide", "tutorial"]):
            return ValueCategory.DOCUMENTATION_CREATED

        # Check for diagram content
        if any(kw in content_lower for kw in ["mermaid", "diagram", "flowchart", "graph"]):
            return ValueCategory.DIAGRAM_GENERATED

        # Check for code patterns
        if any(kw in content_lower for kw in ["pattern", "best practice", "convention"]):
            return ValueCategory.PATTERN_DOCUMENTED

        # Check for test content
        if any(kw in content_lower for kw in ["test", "spec", "assert", "expect"]):
            return ValueCategory.TESTS_WRITTEN

        # Default to insight for unclassified content
        return ValueCategory.INSIGHT_DISCOVERED

    def _calculate_value(
        self,
        category: ValueCategory,
        content: str,
        metadata: Dict[str, Any],
    ) -> float:
        """Calculate value based on category and content metrics."""
        base_value = self.values.get(category, 50.0)

        # Apply content-based multipliers
        multiplier = 1.0

        # Length-based multiplier for documentation and code
        content_length = len(content)
        if category in [
            ValueCategory.CODE_GENERATED,
            ValueCategory.DOCUMENTATION_CREATED,
            ValueCategory.CODE_EXPLAINED,
        ]:
            if content_length > 1000:
                multiplier *= 1.5
            elif content_length > 500:
                multiplier *= 1.2

        # Impact-based multiplier from metadata
        impact = metadata.get("impact", "medium")
        if impact == "high":
            multiplier *= 2.0
        elif impact == "critical":
            multiplier *= 3.0
        elif impact == "low":
            multiplier *= 0.5

        # Priority-based multiplier
        priority = metadata.get("priority", "")
        if priority in ["must", "critical"]:
            multiplier *= 1.5
        elif priority in ["could", "wont"]:
            multiplier *= 0.7

        # Severity multiplier for prevention categories
        severity = metadata.get("severity", "")
        if category in [
            ValueCategory.SECURITY_ISSUE_FOUND,
            ValueCategory.BUG_PREVENTED,
            ValueCategory.PERFORMANCE_ISSUE_FOUND,
        ]:
            if severity == "critical":
                multiplier *= 5.0
            elif severity == "high":
                multiplier *= 2.0
            elif severity == "low":
                multiplier *= 0.3

        return round(base_value * multiplier, 2)

    def _calculate_confidence(
        self,
        category: ValueCategory,
        content: str,
        metadata: Dict[str, Any],
    ) -> float:
        """Calculate confidence score for the attribution."""
        confidence = 0.7  # Base confidence

        # Higher confidence for artifacts with clear type mapping
        if ARTIFACT_TYPE_MAPPING.get(metadata.get("type", "")) == category:
            confidence += 0.1

        # Higher confidence when we have supporting evidence
        if metadata.get("trace_id"):
            confidence += 0.05
        if metadata.get("artifact_id"):
            confidence += 0.05
        if metadata.get("spec_id"):
            confidence += 0.05

        # Content-based confidence adjustments
        content_lower = content.lower()

        # Higher confidence for specific technical content
        if category == ValueCategory.SECURITY_ISSUE_FOUND:
            if any(kw in content_lower for kw in ["cve", "owasp", "vulnerability"]):
                confidence += 0.1

        if category == ValueCategory.DIAGRAM_GENERATED:
            if "mermaid" in content_lower or "```" in content:
                confidence += 0.1

        return min(confidence, 1.0)

    def _build_evidence(self, metadata: Dict[str, Any]) -> List[str]:
        """Build list of evidence references from metadata."""
        evidence = []

        if trace_id := metadata.get("trace_id"):
            evidence.append(f"trace:{trace_id}")

        if artifact_id := metadata.get("artifact_id") or metadata.get("id"):
            evidence.append(f"artifact:{artifact_id}")

        if spec_id := metadata.get("spec_id"):
            evidence.append(f"spec:{spec_id}")

        if storage_path := metadata.get("storage_path"):
            evidence.append(f"file:{storage_path}")

        return evidence

    def attribute_artifacts(
        self,
        artifacts: List[Dict[str, Any]],
    ) -> ValueBreakdownExpanded:
        """
        Attribute value to a list of artifacts.

        Args:
            artifacts: List of artifact dictionaries

        Returns:
            ValueBreakdownExpanded with aggregated values
        """
        breakdown = ValueBreakdownExpanded()

        for artifact in artifacts:
            artifact_type = artifact.get("type", "unknown")
            content = artifact.get("content", "")

            attribution = self.attribute_value(
                artifact_type=artifact_type,
                content=content,
                metadata=artifact,
            )

            breakdown.add_attribution(attribution)

        return breakdown

    def get_breakdown_by_project(
        self,
        attributions: List[ValueAttribution],
    ) -> Dict[str, ValueBreakdownExpanded]:
        """
        Group attributions by project and return breakdowns.

        Args:
            attributions: List of ValueAttribution objects

        Returns:
            Dictionary mapping project_id to ValueBreakdownExpanded
        """
        by_project: Dict[str, ValueBreakdownExpanded] = {}

        for attr in attributions:
            project_id = attr.metadata.get("project_id", "default")

            if project_id not in by_project:
                by_project[project_id] = ValueBreakdownExpanded()

            by_project[project_id].add_attribution(attr)

        return by_project

    def get_breakdown_by_feature_type(
        self,
        attributions: List[ValueAttribution],
    ) -> Dict[str, ValueBreakdownExpanded]:
        """
        Group attributions by feature type (build, spec, insights, etc.).

        Args:
            attributions: List of ValueAttribution objects

        Returns:
            Dictionary mapping feature_type to ValueBreakdownExpanded
        """
        by_feature: Dict[str, ValueBreakdownExpanded] = {}

        for attr in attributions:
            feature_type = attr.metadata.get("feature_type", "other")

            if feature_type not in by_feature:
                by_feature[feature_type] = ValueBreakdownExpanded()

            by_feature[feature_type].add_attribution(attr)

        return by_feature
