@dataclass
class ValueAttribution:
    """
    Represents a value attribution for a specific artifact or action.

    Attributes:
        category: The granular value category
        parent_type: The parent type (execution, decision, prevention, knowledge)
        value_usd: The estimated value in USD
        confidence: Confidence score (0-1) for the attribution
        evidence: List of links/references to artifacts or traces that support this attribution
        metadata: Additional metadata about the attribution
        timestamp: When the value was attributed
    """
    category: ValueCategory
    parent_type: str
    value_usd: float
    confidence: float = 0.8
    evidence: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)
    timestamp: datetime = field(default_factory=datetime.utcnow)

    def __post_init__(self):
        """Ensure parent_type matches category if not provided."""
        if not self.parent_type:
            self.parent_type = CATEGORY_PARENT_MAP.get(self.category, "other")

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "category": self.category.value,
            "parent_type": self.parent_type,
            "value_usd": self.value_usd,
            "confidence": self.confidence,
            "evidence": self.evidence,
            "metadata": self.metadata,
            "timestamp": self.timestamp.isoformat(),
        }


@dataclass
class ValueBreakdownExpanded:
    """
    Expanded value breakdown with subcategory details.

    Contains aggregated values by parent type and detailed
    breakdown by subcategory.
    """
    # Parent type totals
    execution_value: float = 0.0
    decision_value: float = 0.0
    prevention_value: float = 0.0
    knowledge_value: float = 0.0

    # Subcategory breakdowns
    by_subcategory: Dict[str, float] = field(default_factory=dict)

    # Attribution details
    attributions: List[ValueAttribution] = field(default_factory=list)

    @property
    def total_value(self) -> float:
        """Calculate total value across all categories."""
        return (
            self.execution_value +
            self.decision_value +
            self.prevention_value +
            self.knowledge_value
        )

    def add_attribution(self, attribution: ValueAttribution) -> None:
        """Add an attribution and update totals."""
        self.attributions.append(attribution)

        # Update subcategory
        cat_key = attribution.category.value
        self.by_subcategory[cat_key] = self.by_subcategory.get(cat_key, 0) + attribution.value_usd

        # Update parent type total
        if attribution.parent_type == "execution":
            self.execution_value += attribution.value_usd
        elif attribution.parent_type == "decision":
            self.decision_value += attribution.value_usd
        elif attribution.parent_type == "prevention":
            self.prevention_value += attribution.value_usd
        elif attribution.parent_type == "knowledge":
            self.knowledge_value += attribution.value_usd

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "execution_value": self.execution_value,
            "decision_value": self.decision_value,
            "prevention_value": self.prevention_value,
            "knowledge_value": self.knowledge_value,
            "total_value": self.total_value,
            "by_subcategory": self.by_subcategory,
            "attribution_count": len(self.attributions),
        }


