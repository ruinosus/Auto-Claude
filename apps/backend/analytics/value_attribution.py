"""
Value Attribution System
========================

Expanded value categorization system with granular subcategories for
tracking the specific types of value generated by Auto-Claude features.

This module provides:
- ValueCategory enum with granular subcategories for execution, decision,
  prevention, and knowledge value types
- ValueAttribution dataclass for representing attributed value with evidence
- ValueAttributionService for mapping artifacts to value categories

Value Categories:
1. EXECUTION - Direct work done (code, boilerplate, refactoring)
2. DECISION - Strategic choices (feature prioritization, architecture, tech)
3. PREVENTION - Problems avoided (bugs, security, performance, rework)
4. KNOWLEDGE - Learning gained (docs, diagrams, onboarding, patterns)
"""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Dict, List, Optional, Any


class ValueCategory(Enum):
    """
    Granular value categories with subcategories for detailed attribution.

    Parent types:
    - execution: Direct work value
    - decision: Strategic value
    - prevention: Problem avoidance
    - knowledge: Learning value
    """

