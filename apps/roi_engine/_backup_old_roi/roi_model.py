    EXECUTION = "execution"      # Direct work value (code, implementation)
    DECISION = "decision"        # Strategic value (prioritization, viability)
    PREVENTION = "prevention"    # Problem avoidance (bugs, security)
    KNOWLEDGE = "knowledge"      # Learning value (insights, exploration)


