@dataclass
class UnifiedROI:
    """
    Universal ROI structure for any Auto-Claude feature.

    This model captures value across all dimensions:
    - Execution (direct work done)
    - Decision (strategic choices made)
    - Prevention (problems avoided)
    - Knowledge (learning gained)
    """
    # Identification
    feature_type: FeatureType
    spec_id: Optional[str] = None
    project_id: Optional[str] = None
    trace_id: Optional[str] = None
    timestamp: datetime = field(default_factory=datetime.utcnow)

    # Cost (universal)
    cost: CostMetrics = field(default_factory=CostMetrics)

    # Value breakdown by type
    value_breakdown: Dict[ValueType, float] = field(default_factory=dict)

    # Feature-specific metrics (only one will be populated)
    ideation_metrics: Optional[IdeationMetrics] = None
    roadmap_metrics: Optional[RoadmapMetrics] = None
    spec_metrics: Optional[SpecMetrics] = None
    build_metrics: Optional[BuildMetrics] = None
    github_metrics: Optional[GitHubMetrics] = None
    insights_metrics: Optional[InsightsMetrics] = None
    merge_metrics: Optional[MergeMetrics] = None

    # Calculated fields
    total_value_usd: float = 0.0
    roi_percentage: float = 0.0
    confidence_score: float = 0.0  # 0-1, how confident we are in the estimate

    # Additional metadata
    tags: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def calculate_total_value(self) -> float:
        """Calculate total value from all value types."""
        self.total_value_usd = sum(self.value_breakdown.values())
        return self.total_value_usd

    def calculate_roi(self) -> float:
        """Calculate ROI percentage."""
        if self.cost.total_cost_usd > 0:
            self.roi_percentage = (
                (self.total_value_usd - self.cost.total_cost_usd)
                / self.cost.total_cost_usd * 100
            )
        else:
            self.roi_percentage = 0.0 if self.total_value_usd == 0 else float('inf')
        return self.roi_percentage

    def to_langfuse_scores(self) -> Dict[str, float]:
        """Convert to Langfuse score format for storage."""
        scores = {
            "roi_percentage": self.roi_percentage,
            "total_value_usd": self.total_value_usd,
            "total_cost_usd": self.cost.total_cost_usd,
            "confidence_score": self.confidence_score,
        }

        # Add value breakdown
        for value_type, value in self.value_breakdown.items():
            scores[f"value_{value_type.value}_usd"] = value

        # Add feature-specific metrics
        if self.build_metrics:
            scores["lines_added"] = float(self.build_metrics.lines_added)
            scores["lines_removed"] = float(self.build_metrics.lines_removed)
            scores["files_changed"] = float(self.build_metrics.files_changed)
            scores["qa_attempts"] = float(self.build_metrics.qa_attempts)
            scores["qa_passed"] = 1.0 if self.build_metrics.qa_passed else 0.0

        if self.ideation_metrics:
            scores["ideas_generated"] = float(self.ideation_metrics.ideas_generated)
            scores["high_impact_ideas"] = float(self.ideation_metrics.high_impact_ideas)

        if self.roadmap_metrics:
            scores["features_identified"] = float(self.roadmap_metrics.features_identified)
            scores["features_rejected"] = float(self.roadmap_metrics.features_rejected)

        if self.github_metrics:
            scores["prs_reviewed"] = float(self.github_metrics.prs_reviewed)
            scores["issues_triaged"] = float(self.github_metrics.issues_triaged)

        if self.merge_metrics:
            scores["conflicts_resolved"] = float(self.merge_metrics.conflicts_resolved)
            scores["files_merged"] = float(self.merge_metrics.files_merged)
            scores["manual_intervention_avoided"] = float(self.merge_metrics.manual_intervention_avoided)
            scores["merge_decisions"] = float(self.merge_metrics.merge_decisions)
            scores["code_choices"] = float(self.merge_metrics.code_choices)

        return scores


