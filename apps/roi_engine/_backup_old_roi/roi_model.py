"""
Unified ROI Model
==================

Defines a universal ROI structure that works across all Auto-Claude features:
- Ideation (code improvements, security, performance, etc.)
- Roadmap (feature prioritization, strategic decisions)
- Spec (requirements clarity, reduced rework)
- Build (code generation, dev hours saved)
- QA (bugs prevented, quality assurance)
- GitHub (PR review, issue triage)
- Insights (codebase exploration, knowledge transfer)

Each feature type contributes to ROI in different ways:
1. EXECUTION_VALUE: Direct value from work done (code generated, hours saved)
2. DECISION_VALUE: Value from making/not making decisions (prioritization, viability)
3. PREVENTION_VALUE: Value from preventing problems (bugs, security issues)
4. KNOWLEDGE_VALUE: Value from knowledge gain (insights, exploration)
"""

